#!/usr/bin/env python3
"""Compile the shared content pilot. Never edit baseline rules or publish a build.

The first supported edit is one entity's build cost. A null cost inherits the
foundation. Bindings are reviewed source data, never client-supplied paths.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('content/shared-content.json')
OUTPUT = Path('mods/rtsai/shared-content')
TARGETS = {
    'classic-desktop': ('rtsai-classic-core', 'E6', 400),
    'classic-web': ('rtsai-topdown', 'engineer', 500),
    'ra2-desktop': ('rtsai-ra2', 'engineer', 500),
    'ra2-web': ('rtsai', 'engineer', 500),
}


def validate(data):
    if set(data) != {'schema', 'entities'} or data['schema'] != 1:
        raise ValueError('Unsupported shared content schema')
    # This is an intentionally narrow pilot, not an arbitrary YAML/code writer.
    if set(data['entities']) != {'engineer'}:
        raise ValueError('Only the reviewed engineer entity is supported by this pilot')
    entity = data['entities']['engineer']
    if set(entity) != {'cost', 'bindings'}:
        raise ValueError('Unknown entity fields')
    cost = entity['cost']
    if cost is not None and (type(cost) is not int or not 1 <= cost <= 100000):
        raise ValueError('Cost must be an integer from 1 to 100000, or null to inherit')
    expected = {key: dict(mod=mod, actor=actor, baselineCost=baseline)
                for key, (mod, actor, baseline) in TARGETS.items()}
    if entity['bindings'] != expected:
        raise ValueError('Target bindings differ from the reviewed pilot bindings')
    return data


def revision(data):
    validate(data)
    return hashlib.sha256(json.dumps(data, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def read(root=ROOT):
    return validate(json.loads((root / SOURCE).read_text(encoding='utf-8-sig')))


def compiled(data):
    rev = revision(data)
    entity = data['entities']['engineer']
    files = {}
    targets = {}
    for key, (mod, actor, baseline) in TARGETS.items():
        cost = entity['cost']
        # A comment-only file is a valid empty OpenRA rules overlay.
        yaml = f'# Generated by tools/shared-content.py; revision {rev}\n'
        if cost is not None:
            yaml += f'{actor}:\n\tValued:\n\t\tCost: {cost}\n'
        name = f'{key}.yaml'
        files[OUTPUT / name] = yaml
        targets[key] = dict(mod=mod, actor=actor, baselineCost=baseline,
                            cost=baseline if cost is None else cost,
                            rules=f'ra2|shared-content/{name}',
                            rulesSha256=hashlib.sha256(yaml.encode()).hexdigest())
    manifest = dict(schema=1, revision=rev, entity='engineer', overrideCost=entity['cost'], targets=targets)
    files[OUTPUT / 'manifest.json'] = json.dumps(manifest, indent=2) + '\n'
    return files, manifest


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.tmp')
    temp.write_text(text, encoding='utf-8', newline='\n')
    os.replace(temp, path)


def compile_content(root=ROOT, check=False):
    files, manifest = compiled(read(root))
    for target in manifest['targets'].values():
        text = '\n' + (root / 'mods' / target['mod'] / 'mod.yaml').read_text(encoding='utf-8')
        if '\nRules:\n' not in text:
            raise ValueError(f"{target['mod']} has no rules section")
        rules = text.split('\nRules:\n', 1)[1].split('\nSequences:', 1)[0]
        if f"\t{target['rules']}\n" not in rules:
            raise ValueError(f"{target['mod']} does not load its shared content overlay")
    for rel, text in files.items():
        path = root / rel
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                raise ValueError(f'Stale shared content output: {rel}')
        else:
            atomic_write(path, text)
    return manifest


def edit(root, base_revision, cost):
    # Exclusive ownership plus optimistic revision check prevents lost writes.
    lock = root / 'content/shared-content.lock'
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError as error:
        raise ValueError('Shared content is being edited; retry after the current edit completes') from error
    try:
        os.close(fd)
        data = read(root)
        before = revision(data)
        if not re.fullmatch('[a-f0-9]{64}', base_revision) or before != base_revision:
            raise ValueError('Content changed since it was opened; reload before saving')
        previous = json.dumps(data, indent=2) + '\n'
        data['entities']['engineer']['cost'] = cost
        validate(data)
        # Preserve exact old and new revisions; resetting to inherit is also a revision.
        atomic_write(root / f'content/revisions/{before}.json', previous)
        new_source = json.dumps(data, indent=2) + '\n'
        atomic_write(root / SOURCE, new_source)
        try:
            result = compile_content(root)
        except Exception:
            atomic_write(root / SOURCE, previous)
            for rel, text in compiled(json.loads(previous))[0].items():
                atomic_write(root / rel, text)
            raise
        atomic_write(root / f"content/revisions/{result['revision']}.json", new_source)
        return result
    finally:
        lock.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['show', 'compile', 'check', 'edit'])
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--base-revision')
    parser.add_argument('--cost', type=int)
    parser.add_argument('--inherit', action='store_true')
    args = parser.parse_args()
    root = args.root.resolve()
    if args.command == 'show':
        result = compiled(read(root))[1]
    elif args.command == 'edit':
        if not args.base_revision or (args.cost is None) == (not args.inherit):
            parser.error('edit needs --base-revision and exactly one of --cost or --inherit')
        result = edit(root, args.base_revision, None if args.inherit else args.cost)
    else:
        result = compile_content(root, check=args.command == 'check')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(2)

#!/usr/bin/env python3
"""Mode-specific unit overrides. Preserves all existing shared content and base rules."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import importlib.util

_spec = importlib.util.spec_from_file_location('unit_details', Path(__file__).with_name('unit-details.py'))
details = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(details)

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('content/unit-modifications.json')
REGISTRY = Path('content/unit-bindings.json')
OUTPUT = Path('mods/rtsai/unit-overrides')
MODS = {'classic-desktop': 'rtsai-classic-core', 'classic-web': 'rtsai-classic-core', 'ra2-desktop': 'rtsai-ra2', 'ra2-web': 'rtsai'}
FIELDS = {'cost': ('Valued', 'Cost', 100000), 'health': ('Health', 'HP', 10000000), 'speed': (None, 'Speed', 1000)}


def load(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def digest(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def validate(source, registry):
    if set(source) != {'schema', 'units'} or source['schema'] != 1 or type(source['units']) is not dict:
        raise ValueError('Invalid unit modification source')
    for key, values in source['units'].items():
        if key not in registry['units'] or type(values) is not dict or not values or set(values) - set(FIELDS):
            raise ValueError('Unsupported unit or stat')
        for field, value in values.items():
            if type(value) is not int or not 1 <= value <= FIELDS[field][2]:
                raise ValueError(f'{field} must be a positive integer up to {FIELDS[field][2]}')
            for target, binding in registry['units'][key]['bindings'].items():
                if target not in MODS or not re.fullmatch(r'[a-zA-Z0-9_.-]+', binding['actor']):
                    raise ValueError('Invalid reviewed binding')
                if binding['baseline'].get(field) is None or (field == 'speed' and binding['speedTrait'] not in ('Mobile', 'Aircraft')):
                    raise ValueError(f'{field} is not supported for every bound target')


def state(root):
    source, registry = load(root / SOURCE), load(root / REGISTRY)
    validate(source, registry)
    full = details.load(root)
    details.validate(full, registry)
    identity = {'source': source, 'bindings': registry, 'inherited': load(root / 'content/shared-content.json')}
    if full['units']: identity['details'] = full
    return source, registry, digest(identity)


def compiled(root):
    source, registry, revision = state(root)
    actors = {target: {} for target in MODS}
    for key, values in sorted(source['units'].items()):
        for target, binding in registry['units'][key]['bindings'].items():
            actor = actors[target].setdefault(binding['actor'], {})
            for field, value in values.items():
                trait, prop, _ = FIELDS[field]
                actor.setdefault(trait or binding['speedTrait'], {})[prop] = value
    files = {}
    actor_details, weapon_details = details.compile_overlays(root, registry)
    for target, units in actors.items():
        text = f'# Generated by tools/unit-content.py; revision {revision}\n'
        for actor, traits in sorted(units.items()):
            text += f'{actor}:\n'
            for trait, fields in traits.items():
                text += f'\t{trait}:\n' + ''.join(f'\t\t{field}: {value}\n' for field, value in fields.items())
        files[OUTPUT / f'{target}.yaml'] = text + actor_details.get(target, '')
        files[OUTPUT / f'{target}-weapons.yaml'] = f'# Generated unit weapon variants; revision {revision}\n' + weapon_details.get(target, '')
    manifest = {'schema': 1, 'revision': revision, 'units': source['units'], 'bindingsRevision': digest(registry),
                'targets': {target: {'mod': mod, 'rules': f'ra2|unit-overrides/{target}.yaml',
                            'sha256': hashlib.sha256(files[OUTPUT / f'{target}.yaml'].encode()).hexdigest()} for target, mod in MODS.items()}}
    manifest['details'] = details.load(root)['units']
    files[OUTPUT / 'manifest.json'] = json.dumps(manifest, indent=2) + '\n'
    files[OUTPUT / 'bindings.json'] = json.dumps(registry, indent=2) + '\n'
    return files, manifest


def atomic(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.tmp')
    temp.write_text(text, encoding='utf-8', newline='\n')
    os.replace(temp, path)


def compile_content(root, check=False):
    files, manifest = compiled(root)
    for target, mod in MODS.items():
        yaml = '\n' + (root / 'mods' / mod / 'mod.yaml').read_text(encoding='utf-8')
        if '\nRules:\n' not in yaml:
            raise ValueError(f'{mod} has no rules section')
        rules = yaml.split('\nRules:\n', 1)[1].split('\nSequences:', 1)[0]
        if f'\tra2|unit-overrides/{target}.yaml\n' not in rules:
            raise ValueError(f'{mod} does not load unit modifications')
    for path, text in files.items():
        if check:
            if not (root / path).exists() or (root / path).read_text(encoding='utf-8') != text:
                raise ValueError(f'Stale unit modification output: {path}')
        else:
            atomic(root / path, text)
    return manifest


def view(root, key):
    source, registry, revision = state(root)
    if key not in registry['units']:
        return {'supported': False, 'revision': revision, 'reason': 'No reviewed gameplay binding for this unit yet.'}
    unit = registry['units'][key]
    pilot = load(root / 'content/shared-content.json')['entities']['engineer']
    targets = {}
    values = source['units'].get(key, {})
    for target, binding in unit['bindings'].items():
        inherited = dict(binding['baseline'])
        for field, parents in binding.get('inheritance', {}).items():
            for parent in parents:
                parent_values = source['units'].get(f"{unit['mode']}:{parent}", {})
                if field in parent_values:
                    inherited[field] = parent_values[field]
                    break
        pilot_binding = pilot['bindings'].get('classic-desktop' if target == 'classic-web' else target)
        if pilot_binding and binding['actor'].lower() == pilot_binding['actor'].lower() and pilot['cost'] is not None:
            inherited['cost'] = pilot['cost']
        targets[target] = {**binding, 'inherited': inherited, 'effective': {**inherited, **values}}
    related = [{'key': other_key, 'name': other['name'], 'fields': sorted(field for field in values
                if unit['actor'] in other['bindings'].get(f"{unit['mode']}-desktop", {}).get('inheritance', {}).get(field, []))}
               for other_key, other in registry['units'].items() if other['mode'] == unit['mode'] and other_key != key]
    return {'supported': True, 'revision': revision, 'key': key, 'unit': unit, 'overrides': values, 'targets': targets,
            'relatedUnits': [entry for entry in related if entry['fields']]}


def edit(root, body):
    if type(body) is not dict or set(body) not in ({'unit', 'baseRevision', 'values'}, {'unit', 'baseRevision', 'values', 'details'}):
        raise ValueError('Expected unit, baseRevision and values')
    key, values = body['unit'], body['values']
    lock = root / 'content/unit-modifications.lock'
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError as error:
        raise ValueError('Content is being edited') from error
    try:
        os.close(fd)
        source, registry, revision = state(root)
        if body['baseRevision'] != revision:
            raise ValueError('Content changed since it was opened')
        if key not in registry['units'] or type(values) is not dict or set(values) - set(FIELDS):
            raise ValueError('Unsupported unit or stat')
        previous = (root / SOURCE).read_text(encoding='utf-8')
        previous_details = details.load(root)
        old_files, _ = compiled(root)
        if values:
            source['units'][key] = values
        else:
            source['units'].pop(key, None)
        full = details.load(root)
        if 'details' in body:
            change = body['details']
            if change == {'actor': '', 'weapons': {}}:
                full['units'].pop(key, None)
            else: full['units'][key] = change
        validate(source, registry)
        details.validate(full, registry)
        atomic(root / f'content/unit-revisions/{revision}.json', previous)
        atomic(root / f'content/unit-revisions/{revision}-details.json', json.dumps(previous_details, indent=2) + '\n')
        atomic(root / SOURCE, json.dumps(source, indent=2) + '\n')
        atomic(root / details.SOURCE, json.dumps(full, indent=2) + '\n')
        try:
            result = compile_content(root)
            if 'details' in body and full['units']:
                details.check_engine(root, registry, full)
            atomic(root / f"content/unit-revisions/{result['revision']}.json", json.dumps(source, indent=2) + '\n')
            atomic(root / f"content/unit-revisions/{result['revision']}-details.json", json.dumps(full, indent=2) + '\n')
        except Exception:
            atomic(root / SOURCE, previous)
            atomic(root / details.SOURCE, json.dumps(previous_details, indent=2) + '\n')
            for path, text in old_files.items():
                atomic(root / path, text)
            raise
        return view(root, key)
    finally:
        lock.unlink()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('command', choices=['compile', 'check', 'view', 'edit', 'workspace'])
    ap.add_argument('--root', type=Path, default=ROOT)
    ap.add_argument('--unit')
    a = ap.parse_args()
    root = a.root.resolve()
    result = view(root, a.unit) if a.command in ['view', 'workspace'] else edit(root, json.load(sys.stdin)) if a.command == 'edit' else compile_content(root, a.command == 'check')
    if a.command == 'workspace' and result['supported']:
        result['details'] = details.view(root, a.unit, load(root / REGISTRY))
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(2)

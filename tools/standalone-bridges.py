#!/usr/bin/env python3
"""Original isometric bridge sprites, generated from project-authored geometry.

No source pictures or game pixels are used. Coordinates use the standalone
terrain's 30 x 15 px cell basis. Span width, directions and sequence names come
from the existing OpenRA bridge rules; native connection/repair logic is reused.
Run: python tools/standalone-bridges.py
"""
from pathlib import Path
import hashlib
import json
import random
from PIL import Image, ImageDraw
from PIL.PngImagePlugin import PngInfo

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'mods/rtsai/standalone/bridges'
W, H, AA = 192, 144, 4


class Scene:
    def __init__(self, turn=False):
        self.turn = turn
        self.faces = []

    def point(self, p):
        x, y, z = p
        if self.turn:
            x, y = y, x
        return ((W / 2 + 30 * (x - y)) * AA, (H / 2 + 15 * (x + y) - 30 * z) * AA)

    def face(self, points, color):
        # The same camera basis as the terrain. Far faces precede nearer ones.
        self.faces.append((sum(x + y + z * .2 for x, y, z in points) / len(points), points, color))

    def box(self, x0, y0, z0, x1, y1, z1, color):
        c = color
        self.face([(x1,y0,z0),(x1,y1,z0),(x1,y1,z1),(x1,y0,z1)], tuple(int(v*.66) for v in c))
        self.face([(x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)], tuple(int(v*.79) for v in c))
        self.face([(x0,y0,z1),(x1,y0,z1),(x1,y1,z1),(x0,y1,z1)], c)

    def render(self):
        im = Image.new('RGBA', (W * AA, H * AA))
        d = ImageDraw.Draw(im)
        for _, points, color in sorted(self.faces, key=lambda f: f[0]):
            d.polygon([self.point(p) for p in points], fill=(*color, 255))
        return im.resize((W, H), Image.Resampling.LANCZOS)


def span(wood=False, turn=False, broken='', variation=0, ramp=None, high=False):
    s = Scene(turn)
    rng = random.Random(731 + variation)
    level = .3 if not high else 1.6
    def height(y):
        if ramp == 'a': return level * (.5 + y)
        if ramp == 'b': return level * (.5 - y)
        return level
    # Small deck panels give both a readable silhouette and material detail.
    for i in range(24):
        ya, yb = -.5 + i / 24, -.5 + (i + 1) / 24
        if broken == 'both' and abs((ya + yb)/2) < .26: continue
        if broken == 'a' and ya < -.12: continue
        if broken == 'b' and yb > .12: continue
        shade = rng.randint(-8, 8)
        base = (133+shade, 100+shade, 59+shade) if wood else (92+shade, 96+shade, 94+shade)
        z0, z1 = height(ya), height(yb)
        s.face([(-1.5,ya,z0),(1.5,ya,z0),(1.5,yb,z1),(-1.5,yb,z1)], base)
        s.face([(1.5,ya,z0-.18),(1.5,yb,z1-.18),(1.5,yb,z1),(1.5,ya,z0)], (65,65,59) if not wood else (75,52,29))
        if wood:
            s.face([(-1.5,ya,z0+.008),(1.5,ya,z0+.008),(1.5,ya+.008,z0+.008),(-1.5,ya+.008,z0+.008)], (70,49,28))
        else:
            # Dashed lane stripe runs in the actual travel direction.
            if i % 8 < 4:
                s.face([(-.045,ya,z0+.01),(.045,ya,z0+.01),(.045,yb,z1+.01),(-.045,yb,z1+.01)], (215,192,114))
            for x in [-1.32, 1.27]:
                s.face([(x,ya,z0+.01),(x+.05,ya,z0+.01),(x+.05,yb,z1+.01),(x,yb,z1+.01)], (190,185,160))
    for x in [-1.46, 1.36]:
        for i in range(5):
            y = -.48 + i * .24
            if broken == 'both' and abs(y) < .3 or broken == 'a' and y < -.12 or broken == 'b' and y > .12: continue
            z = height(y)
            s.box(x,y,z-.14,x+.10,y+.035,z+.35, (143,120,77) if wood else (151,158,151))
        for ya, yb in [(-.5,.5)] if not broken else ([(-.5,-.28),(.28,.5)] if broken == 'both' else [(.12,.5)] if broken == 'a' else [(-.5,-.12)]):
            # Open guardrail, leaving the roadway visible.
            s.face([(x,ya,height(ya)+.3),(x+.08,ya,height(ya)+.3),(x+.08,yb,height(yb)+.3),(x,yb,height(yb)+.3)], (155,131,88) if wood else (180,185,177))
    if not ramp:
        for x in [-1.18, 1.05]:
            for y in [-.45,.36]:
                if broken and abs(y) < .3: continue
                s.box(x,y,-.1,x+.16,y+.10,level-.18, (92,68,40) if wood else (118,123,114))
    return s.render()


def hut():
    s = Scene()
    s.box(-.46,-.43,0,.46,.43,.52,(164,153,126))
    s.box(.465,-.26,.03,.48,.05,.36,(60,67,57))
    s.box(-.24,.435,.22,.05,.45,.4,(48,84,91))
    s.face([(-.58,-.55,.52),(0,-.55,.83),(0,.55,.83),(-.58,.55,.52)],(112,125,107))
    s.face([(0,-.55,.83),(.58,-.55,.52),(.58,.55,.52),(0,.55,.83)],(73,88,74))
    s.box(-.5,.46,.05,-.28,.52,.42,(134,113,67))
    return s.render()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    overrides = ['# Generated by tools/standalone-bridges.py. Original geometry; native bridge mechanics.']
    records = []
    for material in ['lobrdg', 'lobrdb']:
        for axis in ['a', 'b']:
            for dead in [False, True]:
                name = f'{material}_{axis}' + ('_d' if dead else '')
                seqs = ['idle','aramp','bramp','abramp','editor'] if dead else ['idle','idle2','idle3','idle4','adead','bdead','abdead']
                frames = [span(material == 'lobrdg', axis == 'b',
                    ('both' if dead else 'a' if seq == 'adead' else 'b' if seq == 'bdead' else 'both' if seq == 'abdead' else ''), i)
                    for i, seq in enumerate(seqs)]
                write(name, frames, seqs, overrides, records)
        for direction in ['ne','nw','se','sw']:
            write(f'{material}_r_{direction}', [span(material == 'lobrdg', direction in ['nw','se'], ramp='a' if direction in ['ne','nw'] else 'b')]*2,
                  ['idle','damaged-idle'], overrides, records)
    for name in ['bridge1','bridge2','bridgb1','bridgb2']:
        write(name, [span(name.startswith('bridgb'), name.endswith('2'), high=True)], ['idle'], overrides, records)
    write('cabhut', [hut()]*2, ['idle','damaged-idle'], overrides, records)
    (OUT/'sequences.yaml').write_text('\n'.join(overrides)+'\n', encoding='utf-8')
    (OUT/'PROVENANCE.json').write_text(json.dumps({
        'generator':'tools/standalone-bridges.py', 'source':'Project-authored 3D polygons, colours and material patterns; no input images.',
        'license':'CC0-1.0', 'projection':'30 px x 15 px cell basis; 192 x 144 frame; centered at native actor center',
        'scope':'Bridge actor artwork only. Ground-level connections, damage, repair and passability remain native OpenRA traits. Elevated actors remain native placeholders.',
        'files':records}, indent=2)+'\n', encoding='utf-8')
    print(f'{len(records)} bridge sheets written to {OUT}')


def write(name, frames, sequences, overrides, records):
    im = Image.new('RGBA',(W*len(frames),H))
    for i, f in enumerate(frames): im.paste(f,(W*i,0))
    meta = PngInfo(); meta.add_text('FrameSize',f'{W},{H}'); meta.add_text('FrameAmount',str(len(frames)))
    path = OUT/f'{name}.png'; im.save(path,pnginfo=meta,optimize=True)
    overrides.extend([f'\n{name}:'])
    for i, seq in enumerate(sequences):
        overrides.extend([f'\t{seq}:'] + ([] if name == 'cabhut' else ['\t\t-TilesetFilenames:']) + [f'\t\tFilename: ra2|standalone/bridges/{name}.png',
            f'\t\tStart: {i}', '\t\tLength: 1', '\t\tOffset: 0, 0, 0', '\t\tShadowStart: -1'])
    records.append({'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'frames':len(frames)})


if __name__ == '__main__': main()

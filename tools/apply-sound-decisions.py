#!/usr/bin/env python3
"""Apply the Sound desk's decisions to the mod: chosen sounds in, rules rewired, provenance recorded.

The local admin viewer's Sound desk (RTSAI-Web) writes the owner's choices to RTSAI-Art/sound-review.json. This tool
reads them and, on a branch of this checkout:

  * copies each chosen file into mods/rtsai/modern-factions/audio/ (new sounds in sd/, replaced voice lines and
    announcer clips in place), loudness-normalised to the class targets in docs/sound-plan.md with ffmpeg:
    voices -16 LUFS, announcer -16 LUFS (IMA ADPCM 22.05 kHz like every shipped announcer clip), weapons, impacts and
    explosions peak -1 dBTP, deploy/UI/movement -20 LUFS; an optional trim from the desk is applied first;
  * records provenance (source, licence, sha256 of source and output, recipe or prompt or text, the slots) in
    modern-factions/audio/PROVENANCE.json and a generated table in docs/audio-provenance.md;
  * rewires the rules without touching balance: weapon Report and warhead ImpactSounds, death explosions, trait
    sounds and voice sets through three generated override files appended to mod.yaml
    (modern-factions/sound-desk-rules.yaml, -weapons.yaml, -voices.yaml), and announcer notification mappings in
    audio/notifications.yaml. A weapon every user agrees on is overridden in place; otherwise each unit gets a
    variant that `Inherits:` the original weapon with only its sounds changed. A check then resolves every armament
    and death weapon before and after and fails if anything but sounds differs;
  * runs the audio provenance check (tools/standalone-audio.py check) and, when this checkout has a built engine,
    the standalone audit (tools/standalone-audit.py).

It refuses EA/Westwood files (RA2 listening references, anything from the RA2 caches), any source whose bytes no longer
match the recorded sha256, and anything without a redistributable licence. It will not write on main or master.

usage: python tools/apply-sound-decisions.py --decisions ../RTSAI-Art/sound-review.json --dry-run
       python tools/apply-sound-decisions.py --decisions ../RTSAI-Art/sound-review.json
Re-running regenerates every sound-desk file from the decisions (a decision taken back removes its files).
"""

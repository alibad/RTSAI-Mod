# ------------------------------------------------------------------------------------------------ MiniYaml
# A port of RTSAI-Web lib/art-lab/miniyaml.ts (itself ported from OpenRA.Game/MiniYaml.cs, GPL-3.0): parse, merge
# later files over earlier ones, resolve Inherits and -removals.
@dataclass
class Node:
    key: str
    value: str | None
    nodes: list["Node"] = field(default_factory=list)
    location: str = ""


def parse(text: str, name: str = "<string>") -> list[Node]:
    lines = []
    for number, line in enumerate(text.splitlines(), 1):
        start = level = spaces = 0
        while start < len(line):
            c = line[start]
            if c == " ":
                spaces += 1
                if spaces >= 4:
                    spaces, level = 0, level + 1
                start += 1
            elif c == "\t":
                level += 1
                start += 1
            else:
                break
        key_len, value_start, value_len = len(line) - start, -1, 0
        for i, c in enumerate(line):
            if value_start < 0 and c == ":":
                value_start, key_len, value_len = i + 1, i - start, len(line) - i - 1
            if c == "#" and (i == 0 or line[i - 1] != "\\"):
                if i <= start + key_len:
                    key_len = i - start
                else:
                    value_len = i - value_start
                break
        key = line[start:start + key_len].strip() if key_len > 0 else ""
        value = None
        if value_start >= 0:
            v = line[value_start:value_start + value_len].strip()
            value = v.replace("\\#", "#") if v else None
        if not key:
            continue
        lines.append((level, key, value, f"{name}:{number}"))
    root: list[Node] = []
    stack: list[tuple[int, list[Node]]] = [(-1, root)]
    for level, key, value, location in lines:
        while len(stack) > 1 and stack[-1][0] >= level:
            stack.pop()
        node = Node(key, value, [], location)
        stack[-1][1].append(node)
        stack.append((level, node.nodes))
    return root


def _merge_partial(a: Node | None, b: Node | None) -> Node | None:
    if a is None:
        return b
    if b is None:
        return a
    return Node(b.key, b.value if b.value is not None else a.value, _merge_nodes(a.nodes, b.nodes), b.location)


def _merge_nodes(existing: list[Node], override: list[Node]) -> list[Node]:
    if not existing:
        return override
    if not override:
        return existing
    out: list[Node] = []
    plain: set[str] = set()
    for n in existing + override:
        if n.key.startswith("-"):
            out.append(n)
            continue
        if n.key not in plain:
            plain.add(n.key)
            out.append(n)
            continue
        prev = max(i for i, x in enumerate(out) if x.key == n.key)
        removal = max((i for i, x in enumerate(out) if x.key == f"-{n.key}"), default=-1)
        if removal > prev:
            out.append(n)
        else:
            out[prev] = _merge_partial(out[prev], n)
    return out


def _merge_self(nodes: list[Node]) -> list[Node]:
    out: list[Node] = []
    index: dict[str, int] = {}
    for n in nodes:
        if n.key in index:
            out[index[n.key]] = _merge_partial(out[index[n.key]], n)
        else:
            index[n.key] = len(out)
            out.append(n)
    return out


def _resolve(node: Node, tree: dict[str, Node], inherited: frozenset) -> list[Node]:
    resolved: list[Node] = []
    for n in node.nodes:
        if n.key == "Inherits" or n.key.startswith("Inherits@"):
            parent = tree.get(n.value or "")
            if parent is None or (n.value in inherited):
                continue  # lenient: the engine's own lint reports a bad parent
            for r in _resolve(parent, tree, inherited | {n.value}):
                _merge_into(r, resolved, tree, inherited | {n.value})
        elif n.key.startswith("-"):
            resolved[:] = [r for r in resolved if r.key != n.key[1:]]
        else:
            _merge_into(n, resolved, tree, inherited)
    return resolved


def _merge_into(n: Node, resolved: list[Node], tree: dict[str, Node], inherited: frozenset):
    at = next((i for i, r in enumerate(resolved) if r.key == n.key), -1)
    merged = _merge_partial(resolved[at] if at >= 0 else None, n)
    merged = Node(merged.key, merged.value, _resolve(merged, tree, inherited), merged.location)
    if at >= 0:
        resolved[at] = merged
    else:
        resolved.append(merged)


def merge(sources: list[list[Node]]) -> dict[str, Node]:
    """Top-level key -> resolved node (MiniYaml.Merge)."""
    combined: list[Node] = []
    for nodes in sources:
        combined = _merge_nodes(combined, _merge_self(nodes))
    tree = {n.key: n for n in combined if not n.key.startswith("-")}
    return {k: Node(k, n.value, _resolve(n, tree, frozenset({k})), n.location) for k, n in tree.items()}


def child(node: Node | None, key: str) -> Node | None:
    return next((n for n in node.nodes if n.key == key), None) if node else None


def value(node: Node | None, key: str) -> str | None:
    c = child(node, key)
    return c.value if c else None


def traits(actor: Node, kind: str) -> list[Node]:
    return [n for n in actor.nodes if n.key == kind or n.key.startswith(kind + "@")]


def items(text: str | None) -> list[str]:
    return [s.strip() for s in (text or "").split(",") if s.strip()]


def strip_sounds(node: Node) -> Node:
    """A node with every sound key (and the desk's own sound-only warheads) removed: what balance depends on."""
    kids = [strip_sounds(n) for n in node.nodes if n.key not in SOUND_KEYS and not n.key.endswith("@SoundDesk")]
    return Node("", node.value, kids)


def strip_actor(actor: Node) -> Node:
    """An actor without its sound keys and weapon pointers (the weapons themselves are compared separately)."""
    kids = []
    for n in actor.nodes:
        kind = n.key.split("@")[0]
        drop = TRAIT_SOUND_KEYS.get(kind, set()) | WEAPON_REFS.get(kind, set())
        kids.append(Node(n.key, n.value, [c for c in n.nodes if c.key not in drop], n.location))
    return Node("", actor.value, kids)


def canon(node: Node) -> str:
    return json.dumps([node.value, sorted((n.key, canon(n)) for n in node.nodes)])


# ------------------------------------------------------------------------------------------------ the mod
class Mod:
    def __init__(self, root: Path, overlay: dict[str, str] | None = None):
        self.root = root
        self.dir = root / "mods" / "rtsai"
        self.overlay = overlay or {}
        self.manifest_text = self.read("mod.yaml")
        manifest = {n.key: n for n in parse(self.manifest_text, "mod.yaml")}
        self.lists = {k: [n.key for n in manifest[k].nodes] if k in manifest else [] for k in ("Rules", "Weapons", "Voices", "Notifications")}
        self.rules, self.rule_src, self.rule_keys = self._load("Rules")
        self.weapons, self.weapon_src, self.weapon_keys = self._load("Weapons")
        self.voices, self.voice_src, self.voice_keys = self._load("Voices")

    def read(self, rel: str) -> str:
        if rel in self.overlay:
            return self.overlay[rel]
        return (self.dir / rel).read_text(encoding="utf-8")

    def exists(self, rel: str) -> bool:
        return rel in self.overlay or (self.dir / rel).exists()

    @staticmethod
    def rel(ref: str) -> str | None:
        return ref.split("|", 1)[1] if ref.startswith("ra2|") else None

    def _load(self, section: str):
        sources, src, keys = [], {}, {}
        for ref in self.lists[section]:
            rel = self.rel(ref)
            if not rel or not self.exists(rel):
                continue
            nodes = parse(self.read(rel), ref)
            sources.append(nodes)
            for n in nodes:
                src.setdefault(n.key.lower(), rel)
                keys.setdefault(n.key.lower(), n.key)
        merged = merge(sources)
        return {k.lower(): v for k, v in merged.items()}, src, keys

    def modern(self, actor: str) -> bool:
        return self.rule_src.get(actor.lower(), "").startswith("modern-factions/") and not actor.startswith("^")

    def actors(self):
        return [(k, v) for k, v in self.rules.items() if not k.startswith("^")]

    def armaments(self, actor: str) -> list[tuple[str, str]]:
        a = self.rules.get(actor.lower())
        return [(n.key, value(n, "Weapon")) for n in traits(a, "Armament") if value(n, "Weapon")] if a else []

    def users(self, weapon: str) -> list[str]:
        w = weapon.lower()
        return [k for k, a in self.actors() if any(x.lower() == w for _, x in self.armaments(k))]

    def death_chain(self, actor: str):
        """(owner actor, [(trait key, field, weapon)]) of the explosion that plays when the actor dies."""
        a = self.rules.get(actor.lower())
        if not a:
            return None
        own = [(t.key, f, value(t, f)) for t in traits(a, "FireWarheadsOnDeath") for f in ("Weapon", "EmptyWeapon") if value(t, f)]
        if own:
            return actor.lower(), own
        for t in traits(a, "SpawnActorOnDeath"):
            husk = (value(t, "Actor") or "").lower()
            h = self.rules.get(husk)
            if not h:
                continue
            falls = [(f.key, "Explosion", value(f, "Explosion")) for f in traits(h, "FallsToEarth") if value(f, "Explosion")]
            if falls:
                return husk, falls
            hw = [(t2.key, f, value(t2, f)) for t2 in traits(h, "FireWarheadsOnDeath") for f in ("Weapon", "EmptyWeapon") if value(t2, f)]
            if hw:
                return husk, hw
        return None

    def impact_warheads(self, weapon: str) -> list[tuple[str, str | None]]:
        """Warheads that play an impact sound, water-only splashes left out (they keep their own sound)."""
        w = self.weapons.get(weapon.lower())

        def water_only(n: Node) -> bool:
            targets = set(items(value(n, "ValidTargets")))
            return bool(targets) and "Water" in targets and not targets & {"Ground", "Air", "Infantry", "Vehicle", "Structure"}
        return [(n.key, n.value) for n in w.nodes if n.key.split("@")[0] == "Warhead" and child(n, "ImpactSounds") and not water_only(n)] if w else []

    def voice_file(self, set_node: Node, clip: str) -> str:
        """The file a voice-set clip plays (no faction prefix: the desk only rewires prefix-free categories)."""
        variant = value(set_node, "DefaultVariant") or ".aud"
        if "|" in clip:
            return "mods/rtsai/" + self.rel(clip + variant)
        return (clip + variant).lower()


# ------------------------------------------------------------------------------------------------ licences and sources
def licence_verdict(licence: str | None, reference: bool = False) -> str:
    """The same rules as RTSAI-Web lib/sound-desk/model.ts licenceVerdict."""
    text = (licence or "").strip()
    if reference or not text:
        return "refused"
    if re.search(r"\bEA\b|Electronic Arts|Westwood|Red Alert 2|LISTENING REFERENCE|never ship|not for shipping|non-?commercial|\bNC\b|BY-NC|research[- ]only|CPML", text, re.I):
        return "refused"
    if re.search(r"Stability AI Community|openai output|gemini output|CC[- ]BY(?!-NC)|Attribution", text, re.I):
        return "conditional"
    if re.search(r"CC0|public domain|\bMIT\b|Apache-2\.0|GPL-3\.0|project output|project code|RTSAI-Mod project", text, re.I):
        return "ok"
    return "refused"


def conditions(licence: str) -> list[str]:
    out = []
    if re.search(r"Stability AI Community", licence, re.I):
        out.append("Stability AI Community License: outputs are ours; free below USD 1M annual revenue")
    if re.search(r"openai output|gemini output", licence, re.I):
        out.append("AI-generated voice: the game must tell players its voices are AI-generated")
    if re.search(r"CC[- ]BY(?!-NC)|Attribution", licence, re.I):
        out.append("attribution required in CREDITS")
    return out


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


@dataclass
class Source:
    path: Path
    chosen: dict
    verdict: str


class Sources:
    """Resolves and vets a decision's chosen sound."""

    def __init__(self, mod: Mod, art: Path, bakeoff: Path | None):
        self.mod, self.art = mod, art
        self.blocked: set[str] = set()
        self.ra2_dirs = [p for p in [bakeoff.parent / "ra2-ref" if bakeoff else None] if p]
        manifest = bakeoff / "manifest.json" if bakeoff else None
        if manifest and manifest.exists():
            for c in json.loads(manifest.read_text(encoding="utf-8")).get("candidates", []):
                if c.get("reference") or c.get("source") == "ra2-reference":
                    for f in (c.get("files") or {}).values():
                        p = bakeoff / f
                        if p.exists():
                            self.blocked.add(sha256(p))
        for d in self.ra2_dirs:
            if d.exists():
                for p in d.rglob("*"):
                    if p.is_file() and p.suffix.lower() in {".wav", ".ogg", ".mp3", ".flac", ".aud"}:
                        self.blocked.add(sha256(p))

    def resolve(self, chosen: dict) -> Source:
        source, raw = chosen.get("source"), chosen.get("path") or ""
        licence = chosen.get("licence") or ""
        verdict = licence_verdict(licence, bool(chosen.get("reference")))
        if verdict == "refused":
            raise Refused(f"licence not redistributable in the game: {licence[:100]!r}")
        if source == "project":
            if not re.match(r"^mods/rtsai/[\w./-]+\.(wav|ogg)$", raw) or ".." in raw:
                raise Refused(f"not a mod path: {raw}")
            path = self.mod.root / raw
        elif source == "regen":
            path = (self.art / raw).resolve()
            if self.art.resolve() not in path.parents:
                raise Refused(f"a regenerated take outside RTSAI-Art: {raw}")
        elif source in ("bakeoff", "cc0"):
            path = Path(raw)
        else:
            raise Refused(f"unknown source {source}")
        low = str(path).replace("\\", "/").lower()
        if "/ra2-ref/" in low or "/.cache/originals" in low or "/classic-originals" in low or "/rtsai-ea-audio" in low:
            raise Refused(f"an EA/RA2 file: {path}")
        if not path.is_file():
            raise Refused(f"missing source file {path}")
        digest = sha256(path)
        if digest in self.blocked:
            raise Refused(f"the bytes of an RA2 listening reference: {path}")
        if chosen.get("sha256") and chosen["sha256"] != digest:
            raise Refused(f"{path.name} changed since it was chosen (sha256 {digest[:12]} != {chosen['sha256'][:12]})")
        return Source(path, {**chosen, "sha256": digest}, verdict)


# ------------------------------------------------------------------------------------------------ audio
def ffmpeg_run(ffmpeg: str, args: list[str]) -> str:
    r = subprocess.run([ffmpeg, "-hide_banner", "-nostats", *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip()[-600:])
    return r.stderr


def render(ffmpeg: str, src: Path, dst: Path, cls: str, trim: dict | None) -> dict:
    """src -> dst, mono, trimmed, normalised to the class target. Returns what was measured and done."""
    pre = ["-ss", str(trim["start"]), "-to", str(trim["end"])] if trim else []
    fades = []
    if trim:
        length = max(0.05, float(trim["end"]) - float(trim["start"]))
        fades = [f"afade=t=in:d=0.005", f"afade=t=out:st={max(0.0, length - 0.03):.3f}:d=0.03"]
    rate, codec = ("22050", "adpcm_ima_wav") if cls == "announcer" else ("44100", "pcm_s16le")
    chain = ",".join(["aformat=channel_layouts=mono", *fades])
    dst.parent.mkdir(parents=True, exist_ok=True)
    if cls == "weapon":
        log = ffmpeg_run(ffmpeg, ["-i", str(src), *pre, "-af", chain + ",ebur128=peak=true", "-f", "null", "-"])
        m = re.findall(r"Peak:\s+(-?[\d.]+|-inf) dBFS", log)
        peak = float(m[-1]) if m and m[-1] != "-inf" else -1.0
        gain = round(-1.0 - peak, 2)
        ffmpeg_run(ffmpeg, ["-y", "-i", str(src), *pre, "-af", f"{chain},volume={gain}dB,alimiter=limit=0.891:level=false", "-ar", rate, "-ac", "1", "-c:a", codec, str(dst)])
        return {"class": "weapon/explosion", "target": "peak -1 dBTP", "measured_true_peak_dbtp": peak, "gain_db": gain}
    target = {"voice": -16.0, "announcer": -16.0, "ui": -20.0}[cls]
    # Integrated loudness by EBU R128 (ffmpeg ebur128), then one gain to the target and a limiter at -1.5 dBFS.
    # (loudnorm needs about 3 s of audio; game lines and blips are shorter.)
    staged = dst.with_suffix(".mono.wav")
    ffmpeg_run(ffmpeg, ["-y", "-i", str(src), *pre, "-af", chain, "-c:a", "pcm_f32le", str(staged)])
    measured = integrated(ffmpeg, staged)
    if measured is None:
        ffmpeg_run(ffmpeg, ["-y", "-i", str(staged), "-ar", rate, "-ac", "1", "-c:a", codec, str(dst)])
        staged.unlink(missing_ok=True)
        return {"class": cls, "target": f"{target} LUFS", "note": "too short or silent to measure: copied"}
    gain = round(target - measured, 2)
    ffmpeg_run(ffmpeg, ["-y", "-i", str(staged), "-af", f"volume={gain}dB,alimiter=limit=0.841:level=false:attack=1:release=30", "-ar", rate, "-ac", "1", "-c:a", codec, str(dst)])
    staged.unlink(missing_ok=True)
    return {"class": cls, "target": f"{target} LUFS integrated, limiter -1.5 dBFS", "measured_lufs": measured, "gain_db": gain, "result_lufs": integrated(ffmpeg, dst)}


def integrated(ffmpeg: str, path: Path) -> float | None:
    m = re.findall(r"^\s+I:\s+(-?[\d.]+) LUFS", ffmpeg_run(ffmpeg, ["-i", str(path), "-af", "ebur128", "-f", "null", "-"]), re.M)
    return float(m[-1]) if m else None


# ------------------------------------------------------------------------------------------------ the plan
def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "sound"


def ref_of(audio_rel: str, with_ext: bool = True) -> str:
    """modern-factions/audio/<rel> as the rules name it."""
    r = f"ra2|modern-factions/audio/{audio_rel}"
    return r if with_ext else re.sub(r"\.wav$", "", r)


@dataclass
class Output:
    rel: str                 # below modern-factions/audio/
    source: Source
    cls: str
    trim: dict | None
    slots: list[str] = field(default_factory=list)
    in_place: bool = False   # replaces an existing voice line or announcer clip
    verbatim: bool = False   # a take the faction's own chain already mastered (announcer)
    record: dict | None = None


class Plan:
    def __init__(self, mod: Mod, sources: Sources):
        self.mod, self.sources = mod, sources
        self.outputs: dict[str, Output] = {}
        self.refused: list[tuple[str, str]] = []
        self.applied: list[str] = []
        self.weapon_sounds: dict[str, dict[str, dict[str, str]]] = {}   # weapon -> actor -> {report|impact: ref}
        self.deaths: dict[str, str] = {}                                # actor -> ref
        self.trait_sounds: dict[str, dict[tuple[str, str], str]] = {}   # actor -> (trait, key) -> ref
        self.voice_clips: dict[str, str] = {}                           # clip file -> ref (rewired, not in place)
        self.notify: dict[str, str] = {}                                # notification -> clip id
        self.slot_files: dict[str, str] = {}

    def output(self, slot: str, src: Source, cls: str, label: str, in_place: str | None = None) -> Output:
        trim = src.chosen.get("trim")
        if in_place:
            key = in_place
            out = Output(in_place, src, cls, trim, in_place=True, verbatim=(cls == "announcer" and src.chosen.get("source") == "regen" and not trim))
        else:
            digest = hashlib.sha256(f"{src.chosen['sha256']}|{json.dumps(trim, sort_keys=True)}|{cls}".encode()).hexdigest()[:10]
            key = f"{SD_DIR}/{slug(label)}-{digest}.wav"
            out = self.outputs.get(key) or Output(key, src, cls, trim)
        out = self.outputs.setdefault(key, out)
        out.slots.append(slot)
        self.slot_files[slot] = key
        return out

    def add(self, slot: str, entry: dict):
        chosen = entry.get("chosen")
        kind, _, rest = slot.partition(":")
        if kind == "notify":
            clip = chosen.get("path") if isinstance(chosen, dict) else None
            if not clip or not re.match(r"^[0-9A-Za-z_-]{1,16}$", clip):
                raise Refused("no clip id")
            missing = [f for f in MODERN if not self.mod.exists(f"modern-factions/audio/eva/{f}/{clip}.wav")]
            if missing:
                raise Refused(f"clip {clip} is missing for {', '.join(missing)}")
            if not re.search(rf"^\t\t{re.escape(rest)}:", self.mod.read("audio/notifications.yaml"), re.M):
                raise Refused(f"no Speech notification {rest}")
            self.notify[rest] = clip
            return
        src = self.sources.resolve(chosen)
        if kind == "fire" or kind == "impact":
            actor, _, weapon = rest.partition(":")
            if not any(w.lower() == weapon.lower() for _, w in self.mod.armaments(actor)):
                raise Refused(f"{actor} no longer fires {weapon}")
            if not self.mod.modern(actor):
                raise Refused(f"{actor} is not a modern-faction unit")
            out = self.output(slot, src, "weapon", f"{kind}-{weapon}")
            part = "report" if kind == "fire" else "impact"
            self.weapon_sounds.setdefault(self.mod.weapon_keys.get(weapon.lower(), weapon), {}).setdefault(actor.lower(), {})[part] = ref_of(out.rel)
        elif kind == "death":
            actor = rest
            if not self.mod.death_chain(actor):
                raise Refused(f"{actor} has no death explosion")
            if not self.mod.modern(actor):
                raise Refused(f"{actor} is not a modern-faction unit")
            out = self.output(slot, src, "weapon", f"death-{actor}")
            self.deaths[actor.lower()] = ref_of(out.rel)
        elif kind == "trait":
            actor, trait, key = rest.split(":")
            a = self.mod.rules.get(actor.lower())
            if not a or not any(child(t, key) for t in traits(a, trait)):
                raise Refused(f"{actor} has no {trait}.{key}")
            if not self.mod.modern(actor):
                raise Refused(f"{actor} is not a modern-faction unit")
            cls = CLASS_OF.get(entry.get("kind", ""), "ui")
            out = self.output(slot, src, cls, f"{trait}-{actor}")
            self.trait_sounds.setdefault(actor.lower(), {})[(trait, key)] = ref_of(out.rel)
        elif kind == "clip":
            file = rest
            if file.startswith("mods/rtsai/modern-factions/audio/") and "/eva/" not in file:
                rel = file[len("mods/rtsai/modern-factions/audio/"):]
                if not self.mod.exists(f"modern-factions/audio/{rel}"):
                    raise Refused(f"{file} is not in the mod")
                self.output(slot, src, "voice", rel, in_place=rel)
            else:
                out = self.output(slot, src, "voice", f"clip-{Path(file).stem}")
                self.voice_clips[file.lower()] = ref_of(out.rel, with_ext=False)
        elif kind == "eva":
            faction, _, clip = rest.partition(":")
            rel = f"eva/{faction}/{clip}.wav"
            if faction not in MODERN or not self.mod.exists(f"modern-factions/audio/{rel}"):
                raise Refused(f"no announcer clip {rel}")
            self.output(slot, src, "announcer", rel, in_place=rel)
        else:
            raise Refused(f"unknown slot kind {kind}")

    # -------------------------------------------------------------------------------------------- rules
    def rules_text(self) -> dict[str, str]:
        weapons: list[str] = []
        actors: dict[str, dict[str, dict[str, str]]] = {}  # actor -> trait -> field -> value
        variants: dict[str, str] = {}

        def actor_set(actor: str, trait: str, fld: str, val: str):
            actors.setdefault(self.mod.rule_keys.get(actor, actor), {}).setdefault(trait, {})[fld] = val

        def sound_override(weapon: str, sounds: dict[str, str], name: str, inherit: bool) -> str:
            lines = [f"{name}:"] + ([f"\tInherits: {weapon}"] if inherit else [])
            if "report" in sounds:
                lines.append(f"\tReport: {sounds['report']}")
            if "impact" in sounds:
                # One sound per hit: the first warhead plays it, the others stop playing theirs (layered warheads
                # with delays would otherwise repeat it).
                heads = self.mod.impact_warheads(weapon)
                for i, (key, kind) in enumerate(heads):
                    lines += [f"\t{key}: {kind}", f"\t\tImpactSounds: {sounds['impact']}" if i == 0 else "\t\t-ImpactSounds:"]
                if not heads:
                    lines += ["\tWarhead@SoundDesk: CreateEffect", f"\t\tImpactSounds: {sounds['impact']}", "\t\tValidTargets: Ground, Water, Air"]
            return "\n".join(lines) + "\n"

        def variant(weapon: str, sounds: dict[str, str]) -> str:
            key = (weapon, json.dumps(sounds, sort_keys=True))
            if key not in variants:
                name = f"{weapon}__sd_{hashlib.sha256(key[1].encode()).hexdigest()[:6]}"
                variants[key] = name
                weapons.append(sound_override(weapon, sounds, name, inherit=True))
            return variants[key]

        # Weapons fired by armaments.
        for weapon, by_actor in sorted(self.weapon_sounds.items()):
            users = self.mod.users(weapon)
            choices = {json.dumps(v, sort_keys=True) for v in by_actor.values()}
            if len(choices) == 1 and set(users) <= set(by_actor) and all(self.mod.modern(u) for u in users):
                weapons.append(sound_override(weapon, next(iter(by_actor.values())), weapon, inherit=False))
                continue
            for actor, sounds in sorted(by_actor.items()):
                name = variant(weapon, sounds)
                for trait_key, w in self.mod.armaments(actor):
                    if w.lower() == weapon.lower():
                        actor_set(actor, trait_key, "Weapon", name)
        # Death explosions: a variant of the death weapon per sound, pointed at by the unit (or its husk).
        for actor, ref in sorted(self.deaths.items()):
            owner, links = self.mod.death_chain(actor)
            for trait_key, fld, weapon in links:
                name = variant(self.mod.weapon_keys.get(weapon.lower(), weapon), {"impact": ref})
                actor_set(owner, trait_key, fld, name)
        # Trait sounds.
        for actor, sounds in sorted(self.trait_sounds.items()):
            a = self.mod.rules[actor]
            for (trait, key), ref in sorted(sounds.items()):
                for t in traits(a, trait):
                    if child(t, key):
                        actor_set(actor, t.key, key, ref)
        # Voice sets: replace a stand-in clip in every modern set that plays it.
        voices: list[str] = []
        if self.voice_clips:
            for set_key, s in sorted(self.mod.voices.items()):
                if not self.mod.voice_src.get(set_key, "").startswith("modern-factions/") or set_key.startswith("^"):
                    continue
                prefixed = child(s, "Prefixes") is not None
                disabled = set(items(value(s, "DisablePrefixes")) + items(value(child(s, "Voices"), "DisablePrefixes")))
                changed = []
                for cat in (child(s, "Voices").nodes if child(s, "Voices") else []):
                    if cat.key in ("DisablePrefixes", "DisableVariants"):
                        continue
                    clips = items(cat.value)
                    new = [self.voice_clips.get(self.mod.voice_file(s, c), c) for c in clips]
                    if new != clips:
                        if prefixed and cat.key not in disabled:
                            raise Refused(f"{self.mod.voice_keys[set_key]}.{cat.key} adds a faction prefix to its clips")
                        changed.append(f"\t\t{cat.key}: {', '.join(new)}")
                if changed:
                    voices.append(f"{self.mod.voice_keys[set_key]}:\n\tVoices:\n" + "\n".join(changed) + "\n")
        rules = [f"{a}:\n" + "".join(f"\t{t}:\n" + "".join(f"\t\t{k}: {v}\n" for k, v in fields.items()) for t, fields in by_trait.items())
                 for a, by_trait in sorted(actors.items())]
        return {GENERATED["Rules"]: rules, GENERATED["Weapons"]: weapons, GENERATED["Voices"]: voices}

    def text_changes(self) -> dict[str, str | None]:
        """Every text file the plan writes: generated overrides (None removes one), mod.yaml and notifications."""
        out: dict[str, str | None] = {}
        blocks = self.rules_text()
        manifest = self.mod.manifest_text
        for section, rel in GENERATED.items():
            body = blocks[rel]
            ref = f"ra2|{rel}"
            listed = ref in self.mod.lists[section]
            if body:
                out[rel] = HEADER + "\n" + "\n".join(body)
                assert_unique(parse(out[rel], rel), rel)
                if not listed:
                    manifest = add_to_section(manifest, section, ref)
            elif listed or self.mod.exists(rel):
                out[rel] = None
                manifest = remove_from_section(manifest, ref)
        if manifest != self.mod.manifest_text:
            out["mod.yaml"] = manifest
        if self.notify:
            text = self.mod.read("audio/notifications.yaml")
            new = text
            for key, clip in sorted(self.notify.items()):
                new = re.sub(rf"^(\t\t{re.escape(key)}:)[ \t]*[^\s#]*", rf"\g<1> {clip}", new, count=1, flags=re.M)
            if new != text:
                out["audio/notifications.yaml"] = new
        return out


def assert_unique(nodes: list[Node], where: str):
    """MiniYaml refuses a key twice among siblings; so does this tool, before the engine would."""
    seen = set()
    for n in nodes:
        if n.key in seen:
            raise Refused(f"{where}: {n.key} twice at {n.location}")
        seen.add(n.key)
        assert_unique(n.nodes, where)


def add_to_section(text: str, section: str, ref: str) -> str:
    """Appends `\\t<ref>` to the first block of a mod.yaml list (before its first blank line)."""
    lines = text.split("\n")
    start = lines.index(f"{section}:")
    end = start + 1
    while end < len(lines) and lines[end].startswith("\t"):
        end += 1
    lines.insert(end, f"\t{ref}")
    return "\n".join(lines)


def remove_from_section(text: str, ref: str) -> str:
    return "\n".join(l for l in text.split("\n") if l.strip() != ref)


# ------------------------------------------------------------------------------------------------ checks
def balance_check(before: Mod, after: Mod) -> list[str]:
    """Every actor's armament and death weapons, resolved, must be identical before and after once sounds are removed."""
    problems = []
    for key, actor in before.actors():
        new = after.rules.get(key)
        if new is None:
            problems.append(f"{key}: missing after the change")
            continue
        if canon(strip_actor(actor)) != canon(strip_actor(new)):
            problems.append(f"{key}: a non-sound trait changed")
        pairs = list(zip([w for _, w in before.armaments(key)], [w for _, w in after.armaments(key)]))
        chain_b, chain_a = before.death_chain(key), after.death_chain(key)
        if chain_b and chain_a:
            pairs += list(zip([w for _, _, w in chain_b[1]], [w for _, _, w in chain_a[1]]))
        for wb, wa in pairs:
            a, b = before.weapons.get(wb.lower()), after.weapons.get(wa.lower())
            if a is None or b is None:
                problems.append(f"{key}: weapon {wb} -> {wa} does not resolve")
            elif canon(strip_sounds(a)) != canon(strip_sounds(b)):
                problems.append(f"{key}: {wb} -> {wa} differs in more than its sounds")
    return problems


# ------------------------------------------------------------------------------------------------ provenance
def source_note(o: Output) -> str:
    c = o.source.chosen
    kind = c.get("source")
    if kind == "bakeoff":
        return f"RTS AI sound bake-off candidate {c.get('id', '')[8:]} ({c.get('engine') or 'see recipe'})"
    if kind == "cc0":
        return f"CC0 recording: {c.get('title')} ({c.get('origin') or 'see SOURCES.json'})"
    if kind == "project":
        return f"existing project sound {c.get('path')}"
    if kind == "regen":
        return f"Sound desk take RTSAI-Art/{c.get('path')}"
    return str(kind)


def provenance_record(o: Output, old: dict | None, regen_meta: dict | None, now: str) -> dict:
    c = o.source.chosen
    desk = {k: v for k, v in {
        "slots": sorted(o.slots), "candidate": c.get("id"), "source": c.get("source"), "source_path": str(c.get("path")),
        "source_sha256": c.get("sha256"), "title": c.get("title"), "recipe": c.get("recipe"), "prompt": c.get("prompt"),
        "origin": c.get("origin"), "trim": o.trim, "normalisation": o.record, "applied_at": now,
        "conditions": conditions(c.get("licence", "")) or None,
    }.items() if v not in (None, [], "")}
    if regen_meta:
        rec = {k: v for k, v in regen_meta.items() if k not in ("slot", "kind", "created", "file", "sha256", "ok", "generator", "previous_text", "faction", "clip")}
        rec.update({"filename": o.rel, "generator": regen_meta.get("generator", "RTSAI-Web Sound desk")})
    else:
        rec = {"filename": o.rel, "source": source_note(o), "license": c.get("licence")}
        if c.get("text"):
            rec["text"] = c["text"]
        if c.get("language"):
            rec["language"] = c["language"]
        if c.get("engine"):
            rec["engine"] = c["engine"]
        if c.get("voice"):
            rec["voice"] = {"speaker": c["voice"]}
        if c.get("seed") is not None:
            rec["seed"] = c["seed"]
    if old:
        rec["replaces"] = {k: old.get(k) for k in ("text", "engine", "license", "generated_at") if old.get(k) is not None}
        for k in ("role", "faction", "clip", "translation"):
            if old.get(k) is not None and k not in rec:
                rec[k] = old[k]
    rec["license"] = rec.get("license") or c.get("licence")
    rec["sha256"] = None  # filled after writing
    rec["sound_desk"] = desk
    return rec


def section_of(o: Output) -> str:
    if o.cls == "announcer":
        return "announcers"
    return "voice_lines" if o.cls == "voice" else "sound_effects"


# ------------------------------------------------------------------------------------------------ main
def git_branch(root: Path) -> str:
    """The checked-out branch (also on a branch with no commits yet), "HEAD" when detached, "" outside git."""
    for cmd in (["git", "symbolic-ref", "--short", "-q", "HEAD"], ["git", "rev-parse", "--abbrev-ref", "HEAD"]):
        try:
            r = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
        except OSError:
            return ""
        if r.returncode == 0 and r.stdout.strip():
            return r.stdout.strip()
    return ""


def unified(rel: str, old: str, new: str | None) -> str:
    return "".join(difflib.unified_diff(old.splitlines(True), (new or "").splitlines(True), f"a/mods/rtsai/{rel}", f"b/mods/rtsai/{rel}" if new is not None else "/dev/null"))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--decisions", type=Path, default=ROOT.parent / "RTSAI-Art" / "sound-review.json")
    ap.add_argument("--art", type=Path, help="RTSAI-Art root (default: the decisions file's folder)")
    ap.add_argument("--mod", type=Path, default=ROOT)
    ap.add_argument("--bakeoff", type=Path, default=Path("D:/rtsai-sound/bakeoff"), help="its RA2 references are refused by hash")
    ap.add_argument("--dry-run", action="store_true", help="print the plan and the diff; write nothing")
    ap.add_argument("--allow-main", action="store_true", help="write even on main/master (normally refused)")
    ap.add_argument("--skip-checks", action="store_true")
    ap.add_argument("--ffmpeg", default=shutil.which("ffmpeg") or "ffmpeg")
    a = ap.parse_args(argv)
    root = a.mod.resolve()
    art = (a.art or a.decisions.parent).resolve()
    branch = git_branch(root)
    if not a.dry_run and branch in ("main", "master") and not a.allow_main:
        print(f"Refusing to write on {branch}: create a branch first (git switch -c sound/<name>).", file=sys.stderr)
        return 2
    decisions = json.loads(a.decisions.read_text(encoding="utf-8")) if a.decisions.exists() else {"slots": {}}
    mod = Mod(root)
    plan = Plan(mod, Sources(mod, art, a.bakeoff if a.bakeoff and a.bakeoff.exists() else None))
    for slot, entry in sorted((decisions.get("slots") or {}).items()):
        chosen = entry.get("chosen")
        if not chosen or chosen == "current":
            continue
        try:
            plan.add(slot, entry)
            plan.applied.append(slot)
        except Refused as r:
            plan.refused.append((slot, str(r)))
    try:
        changes = plan.text_changes()
    except Refused as r:
        print(f"Refused: {r}", file=sys.stderr)
        return 1

    # Balance: resolve everything again with the generated files and compare.
    overlay = {rel: text for rel, text in changes.items() if text is not None}
    after = Mod(root, overlay={**overlay, **{rel: "" for rel, text in changes.items() if text is None}})
    problems = balance_check(mod, after)

    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    print(f"Sound desk decisions: {a.decisions}  ->  {root} ({branch or 'no git'})")
    print(f"{len(plan.applied)} slots to apply, {len(plan.refused)} refused, {len(plan.outputs)} audio files, {len(plan.notify)} notification mappings")
    for slot, reason in plan.refused:
        print(f"  REFUSED {slot}: {reason}")
    for rel, o in sorted(plan.outputs.items()):
        how = "verbatim (already mastered by the faction chain)" if o.verbatim else {"weapon": "peak -1 dBTP", "voice": "-16 LUFS", "announcer": "-16 LUFS, IMA ADPCM 22.05 kHz", "ui": "-20 LUFS"}[o.cls]
        trim = f", trim {o.trim['start']}-{o.trim['end']} s" if o.trim else ""
        print(f"  {'REPLACE' if o.in_place else 'ADD    '} modern-factions/audio/{rel}  <- {o.source.path}  [{o.source.verdict}; {how}{trim}]  for {len(o.slots)} slot(s)")
    for key, clip in sorted(plan.notify.items()):
        print(f"  NOTIFY  {key} -> {clip}")
    for rel, text in changes.items():
        old = mod.read(rel) if mod.exists(rel) else ""
        print(unified(rel, old, text), end="")
    if problems:
        print("BALANCE CHECK FAILED (the rules would change more than sounds):")
        for p in problems[:40]:
            print("  " + p)
        return 1
    print("Balance check: every armament and death weapon resolves identically apart from its sounds.")
    if a.dry_run:
        return 1 if plan.refused else 0

    # ---- write
    audio = mod.dir / "modern-factions" / "audio"
    prov_path = audio / "PROVENANCE.json"
    prov = json.loads(prov_path.read_text(encoding="utf-8"))
    # Files this tool wrote before and no longer needs.
    for rec_list in ("voice_lines", "announcers", "sound_effects"):
        prov[rec_list] = [r for r in prov.get(rec_list, []) if not str(r.get("filename", "")).startswith(f"{SD_DIR}/")]
    if (audio / SD_DIR).exists():
        for p in (audio / SD_DIR).glob("*.wav"):
            if f"{SD_DIR}/{p.name}" not in plan.outputs:
                p.unlink()
    with tempfile.TemporaryDirectory(prefix="sound-desk-") as tmp:
        for rel, o in sorted(plan.outputs.items()):
            dst = audio / rel
            if o.verbatim:
                shutil.copyfile(o.source.path, dst)
                o.record = {"class": "announcer", "note": "copied: mastered by the faction's announcer chain (-16 LUFS, IMA ADPCM 22.05 kHz)"}
            else:
                staged = Path(tmp) / Path(rel).name
                o.record = render(a.ffmpeg, o.source.path, staged, o.cls, o.trim)
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(staged, dst)
            section = section_of(o)
            records = prov.setdefault(section, [])
            old = next((r for r in records if r.get("filename") == rel), None)
            regen = None
            if o.source.chosen.get("source") == "regen":
                meta = o.source.path.parent / "meta.json"
                regen = json.loads(meta.read_text(encoding="utf-8")) if meta.exists() else None
            rec = provenance_record(o, old, regen, now)
            rec["sha256"] = sha256(dst)
            prov[section] = [r for r in records if r.get("filename") != rel] + [rec]
            prov[section].sort(key=lambda r: r.get("filename", ""))
    prov["updated"] = now[:10]
    prov_path.write_text(json.dumps(prov, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for rel, text in changes.items():
        path = mod.dir / rel
        if text is None:
            path.unlink(missing_ok=True)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    write_doc(root, plan)
    print(f"Wrote {len(plan.outputs)} audio files, {len(changes)} rules files and PROVENANCE.json.")
    if a.skip_checks:
        return 1 if plan.refused else 0
    return run_checks(root) or (1 if plan.refused else 0)


def write_doc(root: Path, plan: Plan):
    doc = root / "docs" / "audio-provenance.md"
    if not doc.exists():
        return
    text = doc.read_text(encoding="utf-8")
    rows = [DOC_BEGIN, "", "#### Sound desk replacements", "",
            "Chosen by the owner in the local admin viewer's Sound desk (RTSAI-Art/sound-review.json) and applied by "
            "`tools/apply-sound-decisions.py`; per-file records with source hashes in `modern-factions/audio/PROVENANCE.json`.",
            "", "| File | Slots | Source | Licence |", "|---|---|---|---|"]
    for rel, o in sorted(plan.outputs.items()):
        lic = (o.source.chosen.get("licence") or "").replace("|", "\\|").replace("\n", " ")[:90]
        rows.append(f"| `modern-factions/audio/{rel}` | {len(o.slots)} | {source_note(o).replace('|', chr(92) + '|')} | {lic} |")
    for key, clip in sorted(plan.notify.items()):
        rows.append(f"| `audio/notifications.yaml` {key} | 1 | now plays announcer clip {clip} | - |")
    rows += ["", DOC_END]
    block = "\n".join(rows)
    if DOC_BEGIN in text:
        text = text[:text.index(DOC_BEGIN)] + block + text[text.index(DOC_END) + len(DOC_END):]
    elif plan.outputs or plan.notify:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        return
    doc.write_text(text, encoding="utf-8", newline="\n")


def run_checks(root: Path) -> int:
    py = sys.executable
    print("Checking audio provenance (tools/standalone-audio.py check)...")
    code = subprocess.run([py, str(root / "tools" / "standalone-audio.py"), "check"], cwd=root).returncode
    engine = root / "engine" / "bin" / "OpenRA.Utility.dll"
    if engine.exists():
        print("Running the standalone audit (tools/standalone-audit.py)...")
        out = Path(tempfile.gettempdir()) / "rtsai-sound-desk-audit.json"
        code |= subprocess.run([py, str(root / "tools" / "standalone-audit.py"), "--out", str(out), "--summary"], cwd=root).returncode
    else:
        print("Standalone audit skipped: this checkout has no built engine (make all), so the engine's own yaml and "
              "audio lint (CheckFactionAudio) runs with `make test` where it is built.")
    return code


